// Turns theme.json into the app's look: src/styles/theme.css (colors, corners,
// text size) and src/app/fonts.ts (fonts). Run with: npm run theme
// It also checks every color pair for readability (WCAG contrast) and darkens
// any color that would be hard to read, so a theme can't make the app illegible.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = process.cwd();
const presets = JSON.parse(readFileSync(join(here, 'theme-presets.json'), 'utf8'));

// Fonts the app can use, with their next/font/google names. Fonts without a
// weight list are variable fonts (every weight included).
const FONTS = {
  'Inter': { fn: 'Inter' },
  'Source Sans 3': { fn: 'Source_Sans_3' },
  'DM Sans': { fn: 'DM_Sans' },
  'Space Grotesk': { fn: 'Space_Grotesk' },
  'Nunito': { fn: 'Nunito' },
  'IBM Plex Sans': { fn: 'IBM_Plex_Sans', weight: ['400', '500', '600', '700'] },
  'Fraunces': { fn: 'Fraunces' },
  'Lora': { fn: 'Lora' },
  'Work Sans': { fn: 'Work_Sans' },
  'Atkinson Hyperlegible': { fn: 'Atkinson_Hyperlegible', weight: ['400', '700'] },
  'Poppins': { fn: 'Poppins', weight: ['400', '500', '600', '700'] },
  'Playfair Display': { fn: 'Playfair_Display' },
};
const COLOR_KEYS = ['background', 'surface', 'ink', 'muted', 'border', 'primary', 'primaryInk', 'accent', 'success', 'warning', 'danger'];

// ---------- color math ----------
const hexOk = (h) => typeof h === 'string' && /^#[0-9a-f]{6}$/i.test(h.trim());
const toRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const toHex = (rgb) => '#' + rgb.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('');
const lum = (h) => {
  const [r, g, b] = toRgb(h).map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const mix = (h, target, t) => {
  const a = toRgb(h), b = toRgb(target);
  return toHex(a.map((v, i) => v + (b[i] - v) * t));
};
// Darken (or lighten) `color` until it reaches `min` contrast against every background.
const ensure = (color, backs, min) => {
  let c = color;
  const dark = backs.every((b) => lum(b) > 0.4);
  for (let i = 0; i < 40 && backs.some((b) => contrast(c, b) < min); i++) c = mix(c, dark ? '#000000' : '#ffffff', 0.06);
  return c;
};

// ---------- build the theme ----------
let custom = {};
const themePath = join(root, 'theme.json');
if (existsSync(themePath)) {
  try { custom = JSON.parse(readFileSync(themePath, 'utf8')); } catch { console.error('theme.json is not valid JSON; using the Calm theme.'); }
}
const base = presets[custom.base] ? custom.base : 'calm';
const preset = presets[base];
const colors = { ...preset.colors };
for (const k of COLOR_KEYS) if (hexOk(custom?.colors?.[k])) colors[k] = custom.colors[k].trim().toLowerCase();
const radius = /^\d{1,2}px$/.test(custom.radius ?? '') ? custom.radius : preset.radius;
const fonts = {
  heading: FONTS[custom?.fonts?.heading] ? custom.fonts.heading : preset.fonts.heading,
  body: FONTS[custom?.fonts?.body] ? custom.fonts.body : preset.fonts.body,
};
const textSize = custom.textSize === 'large' ? 'large' : 'normal';

const before = { ...colors };
const backs = [colors.background, colors.surface];
colors.ink = ensure(colors.ink, backs, 7);
colors.muted = ensure(colors.muted, backs, 4.5);
colors.primary = ensure(colors.primary, backs, 4.5); // links and outlines
const white = '#ffffff', black = '#111111';
colors.primaryInk = contrast(white, colors.primary) >= contrast(black, colors.primary) ? white : black;
if (contrast(colors.primaryInk, colors.primary) < 4.5) colors.primary = ensure(colors.primary, [colors.primaryInk], 4.5);
for (const k of ['success', 'warning', 'danger']) colors[k] = ensure(colors[k], [...backs, colors.accent], 4.5);
// Form fields need a border people can see (3:1); dividers can stay subtle.
const fieldBorder = ensure(colors.border, [colors.surface, colors.background], 3);
const adjusted = COLOR_KEYS.filter((k) => before[k] !== colors[k]);

// ---------- write theme.css ----------
const cssVar = (k) => '--' + k.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const css = `/* Generated by scripts/apply-theme.mjs from theme.json (${preset.name} base).
   To change the look, edit theme.json and run: npm run theme
   Don't edit this file by hand; it gets overwritten. */
:root {
${COLOR_KEYS.map((k) => `  ${cssVar(k)}: ${colors[k]};`).join('\n')}
  --field-border: ${fieldBorder};
  --radius: ${radius};
  --text-base-size: ${textSize === 'large' ? '18px' : '16px'};
}

@theme inline {
${COLOR_KEYS.map((k) => `  --color-${cssVar(k).slice(2)}: var(${cssVar(k)});`).join('\n')}
  --color-field-border: var(--field-border);
  --radius-ui: var(--radius);
  --font-heading: var(--font-heading-src), ui-sans-serif, system-ui, sans-serif;
  --font-body: var(--font-body-src), ui-sans-serif, system-ui, sans-serif;
}
`;
mkdirSync(join(root, 'src', 'styles'), { recursive: true });
writeFileSync(join(root, 'src', 'styles', 'theme.css'), css);

// ---------- write fonts.ts ----------
const opts = (name, variable) => {
  const f = FONTS[name];
  const w = f.weight ? `, weight: ${JSON.stringify(f.weight)}` : '';
  return `{ subsets: ["latin"], variable: "${variable}", display: "swap"${w} }`;
};
const same = fonts.heading === fonts.body;
const imports = same ? FONTS[fonts.body].fn : [FONTS[fonts.heading].fn, FONTS[fonts.body].fn].join(', ');
const ts = `// Generated by scripts/apply-theme.mjs from theme.json. To change fonts, edit
// theme.json and run: npm run theme
import { ${imports} } from "next/font/google";

${same
  ? `const bodyFont = ${FONTS[fonts.body].fn}(${opts(fonts.body, '--font-body-src')});
const headingFont = ${FONTS[fonts.heading].fn}(${opts(fonts.heading, '--font-heading-src')});`
  : `const headingFont = ${FONTS[fonts.heading].fn}(${opts(fonts.heading, '--font-heading-src')});
const bodyFont = ${FONTS[fonts.body].fn}(${opts(fonts.body, '--font-body-src')});`}

export const fontVariables = \`\${headingFont.variable} \${bodyFont.variable}\`;
`;
mkdirSync(join(root, 'src', 'app'), { recursive: true });
writeFileSync(join(root, 'src', 'app', 'fonts.ts'), ts);

console.log(`Theme applied: ${custom.name || preset.name} (based on ${preset.name}), fonts ${fonts.heading} / ${fonts.body}, ${textSize} text.`);
if (adjusted.length) console.log(`Adjusted for readability: ${adjusted.join(', ')}.`);
